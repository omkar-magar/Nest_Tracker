-- Guest register: the simple room-by-room tenant list the office kept in the stand-alone "PG Manager" page,
-- now inside the app. A guest needs no login. Each row has rent and deposit with a status, check-in and
-- expected check-out dates and notes. Every change is kept in register_history. Removing a guest checks them
-- out (checked_out_on) instead of deleting, so they stay under "Past guests". Whether a room counts as PG or
-- rented is not stored: it follows from how many guests are in the room (1 = rented, 2 or more = PG).

create table public.register_guests (
  id                bigint generated by default as identity primary key,
  property_id       text not null references public.properties (id) on delete cascade,
  room_no           text not null check (room_no <> ''),
  sort_order        numeric not null default 0,
  name              text not null default '',
  contact           text not null default '' check (contact = '' or contact ~ '^[0-9]{10}$'),
  rent              int check (rent >= 0),
  deposit           int check (deposit >= 0),
  rent_status       text not null default 'not_updated'
                      check (rent_status in ('paid', 'pending', 'partially_paid', 'not_updated', 'not_applicable')),
  deposit_status    text not null default 'not_updated'
                      check (deposit_status in ('paid', 'pending', 'partially_paid', 'not_updated', 'not_applicable')),
  check_in          date,
  expected_checkout date,
  checked_out_on    date,
  checkout_note     text not null default '',
  notes             text not null default '',
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  check (expected_checkout is null or check_in is null or expected_checkout >= check_in)
);
create index register_guests_live_idx on public.register_guests (property_id, room_no) where checked_out_on is null;
create index register_guests_past_idx on public.register_guests (property_id, checked_out_on desc) where checked_out_on is not null;

create table public.register_history (
  id              bigint generated always as identity primary key,
  property_id     text not null,
  guest_id        bigint not null,
  op              text not null check (op in ('INSERT', 'UPDATE', 'DELETE', 'CHECKOUT', 'RETURN')),
  old_row         jsonb,
  new_row         jsonb,
  changed_by      uuid,
  changed_by_name text not null default '',
  changed_at      timestamptz not null default now()
);
create index register_history_property_idx on public.register_history (property_id, changed_at desc);

create function public.register_touch() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;
create trigger register_guests_touch before update on public.register_guests
  for each row execute function public.register_touch();

-- writes the history row whatever the caller's RLS allows
create function public.register_audit() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_op text := tg_op;
  v_old jsonb := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end;
  v_new jsonb := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end;
  r public.register_guests := coalesce(new, old);
begin
  if tg_op = 'UPDATE' then
    if (v_old - 'updated_at') = (v_new - 'updated_at') then return null; end if;
    if old.checked_out_on is null and new.checked_out_on is not null then v_op := 'CHECKOUT';
    elsif old.checked_out_on is not null and new.checked_out_on is null then v_op := 'RETURN';
    end if;
  end if;
  insert into public.register_history (property_id, guest_id, op, old_row, new_row, changed_by, changed_by_name)
  values (r.property_id, r.id, v_op, v_old, v_new, auth.uid(),
          coalesce((select full_name from public.profiles where id = auth.uid()), ''));
  return null;
end $$;
create trigger register_guests_audit after insert or update or delete on public.register_guests
  for each row execute function public.register_audit();

-- ---------------------------------------------------------------- access
-- Owner and the property's managers read and edit. An employee of the property (caretaker) may read when the
-- owner left "view customers" on for them. History is for owner and managers only.
alter table public.register_guests  enable row level security;
alter table public.register_history enable row level security;
grant select, insert, update, delete on public.register_guests to authenticated;
grant select on public.register_history to authenticated;

create policy register_read on public.register_guests for select using (
  public.can_manage_property(property_id)
  or (public.current_app_role() = 'employee' and public.can_access_property(property_id) and public.has_permission('can_view_customers')));
create policy register_insert on public.register_guests for insert with check (public.can_manage_property(property_id));
create policy register_update on public.register_guests for update
  using (public.can_manage_property(property_id)) with check (public.can_manage_property(property_id));
create policy register_delete on public.register_guests for delete using (public.can_manage_property(property_id));
create policy register_history_read on public.register_history for select using (public.can_manage_property(property_id));

-- ---------------------------------------------------------------- RPCs
-- only these keys may be set from the app; anything else in the JSON is ignored
create function public.register_fields(p jsonb, p_allow_checkout boolean default false) returns jsonb
language sql immutable as $$
  select coalesce(jsonb_object_agg(k, v), '{}'::jsonb) from jsonb_each(coalesce(p, '{}'::jsonb)) as e(k, v)
  where k = any (array['room_no', 'name', 'contact', 'rent', 'deposit', 'rent_status', 'deposit_status',
                       'check_in', 'expected_checkout', 'notes']
                 || case when p_allow_checkout then array['checked_out_on', 'checkout_note'] else '{}'::text[] end)
$$;

-- A guest leaves: keep the row, stamp the date. Their bed space frees up in the room counts at once.
create function public.register_checkout(p_id bigint, p_date date default current_date, p_note text default '')
returns void language plpgsql security definer set search_path = public as $$
declare g public.register_guests;
begin
  select * into g from public.register_guests where id = p_id for update;
  if not found then raise exception 'Guest not found'; end if;
  perform public.require_manage(g.property_id);
  if g.checked_out_on is not null then raise exception 'Already checked out on %', g.checked_out_on; end if;
  if p_date is null then raise exception 'Check-out date is required'; end if;
  if g.check_in is not null and p_date < g.check_in then
    raise exception 'Check-out date cannot be before the check-in date (%)', g.check_in;
  end if;
  update public.register_guests set checked_out_on = p_date, checkout_note = coalesce(p_note, '') where id = p_id;
end $$;

-- Undo a check-out (wrong person, or the guest came back)
create function public.register_return(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare g public.register_guests;
begin
  select * into g from public.register_guests where id = p_id for update;
  if not found then raise exception 'Guest not found'; end if;
  perform public.require_manage(g.property_id);
  update public.register_guests set checked_out_on = null, checkout_note = '' where id = p_id;
end $$;

-- Puts a guest back the way they were before one history entry: an add is removed, an edit or check-out is
-- reversed, a deleted row comes back with its old id.
create function public.register_restore(p_history bigint) returns void
language plpgsql security definer set search_path = public as $$
declare h public.register_history; o public.register_guests;
begin
  select * into h from public.register_history where id = p_history;
  if not found then raise exception 'History entry not found'; end if;
  perform public.require_manage(h.property_id);
  if h.op = 'INSERT' then
    delete from public.register_guests where id = h.guest_id;
    return;
  end if;
  o := jsonb_populate_record(null::public.register_guests, h.old_row);
  if o.property_id is distinct from h.property_id then raise exception 'History entry does not match its property'; end if;
  insert into public.register_guests as g (id, property_id, room_no, sort_order, name, contact, rent, deposit, rent_status,
    deposit_status, check_in, expected_checkout, checked_out_on, checkout_note, notes, created_at)
  values (o.id, o.property_id, o.room_no, o.sort_order, o.name, o.contact, o.rent, o.deposit, o.rent_status,
    o.deposit_status, o.check_in, o.expected_checkout, o.checked_out_on, o.checkout_note, o.notes, o.created_at)
  on conflict (id) do update set room_no = excluded.room_no, sort_order = excluded.sort_order, name = excluded.name,
    contact = excluded.contact, rent = excluded.rent, deposit = excluded.deposit, rent_status = excluded.rent_status,
    deposit_status = excluded.deposit_status, check_in = excluded.check_in, expected_checkout = excluded.expected_checkout,
    checked_out_on = excluded.checked_out_on, checkout_note = excluded.checkout_note, notes = excluded.notes
  where g.property_id = excluded.property_id;
end $$;

-- Applies a reviewed list of changes in one go (change links, imports). All or nothing.
-- p_ops: [{"op":"add","set":{...},"after":<guest id>?}, {"op":"update","id":1,"set":{...}},
--         {"op":"checkout","id":1,"date":"2026-11-21","note":""}]
-- p_import lets "add" also carry checked_out_on / checkout_note (past guests from an old register).
create function public.register_apply(p_property text, p_ops jsonb, p_import boolean default false) returns int
language plpgsql security definer set search_path = public as $$
declare
  op jsonb; f jsonb; g public.register_guests; a public.register_guests; n int := 0; v_order numeric; v_next numeric;
begin
  perform public.require_manage(p_property);
  if jsonb_typeof(p_ops) is distinct from 'array' then raise exception 'Changes must be a list'; end if;
  if jsonb_array_length(p_ops) > 500 then raise exception 'Too many changes at once (500 max)'; end if;
  for op in select * from jsonb_array_elements(p_ops) loop
    n := n + 1;
    if op ->> 'op' = 'add' then
      f := public.register_fields(op -> 'set', p_import);
      if coalesce(f ->> 'room_no', '') = '' then raise exception 'Change %: room is required', n; end if;
      select coalesce(max(sort_order), 0) + 1 into v_order from public.register_guests where property_id = p_property;
      if op ? 'after' then
        select * into a from public.register_guests where id = (op ->> 'after')::bigint and property_id = p_property;
        if found and a.room_no = f ->> 'room_no' then
          select min(sort_order) into v_next from public.register_guests
          where property_id = p_property and room_no = a.room_no and sort_order > a.sort_order;
          v_order := case when v_next is null then a.sort_order + 1 else (a.sort_order + v_next) / 2 end;
        end if;
      end if;
      g := jsonb_populate_record(null::public.register_guests,
             f || jsonb_build_object('property_id', p_property, 'sort_order', v_order));
      insert into public.register_guests (property_id, room_no, sort_order, name, contact, rent, deposit, rent_status,
        deposit_status, check_in, expected_checkout, checked_out_on, checkout_note, notes)
      values (p_property, g.room_no, g.sort_order, coalesce(g.name, ''), coalesce(g.contact, ''), g.rent, g.deposit,
        coalesce(g.rent_status, 'not_updated'), coalesce(g.deposit_status, 'not_updated'), g.check_in,
        g.expected_checkout, g.checked_out_on, coalesce(g.checkout_note, ''), coalesce(g.notes, ''));
    elsif op ->> 'op' = 'update' then
      select * into g from public.register_guests where id = (op ->> 'id')::bigint and property_id = p_property for update;
      if not found then raise exception 'Change %: guest not found', n; end if;
      g := jsonb_populate_record(g, public.register_fields(op -> 'set'));
      update public.register_guests set room_no = g.room_no, name = coalesce(g.name, ''), contact = coalesce(g.contact, ''),
        rent = g.rent, deposit = g.deposit, rent_status = g.rent_status, deposit_status = g.deposit_status,
        check_in = g.check_in, expected_checkout = g.expected_checkout, notes = coalesce(g.notes, '')
      where id = g.id;
    elsif op ->> 'op' = 'checkout' then
      if not exists (select 1 from public.register_guests where id = (op ->> 'id')::bigint and property_id = p_property) then
        raise exception 'Change %: guest not found', n;
      end if;
      perform public.register_checkout((op ->> 'id')::bigint, coalesce((op ->> 'date')::date, current_date), coalesce(op ->> 'note', ''));
    else
      raise exception 'Change %: unknown change "%"', n, op ->> 'op';
    end if;
  end loop;
  return n;
end $$;

revoke all on function public.register_touch(), public.register_audit(), public.register_fields(jsonb, boolean),
  public.register_checkout(bigint, date, text), public.register_return(bigint), public.register_restore(bigint),
  public.register_apply(text, jsonb, boolean) from public, anon;
grant execute on function public.register_fields(jsonb, boolean), public.register_checkout(bigint, date, text),
  public.register_return(bigint), public.register_restore(bigint), public.register_apply(text, jsonb, boolean)
  to authenticated, service_role;
